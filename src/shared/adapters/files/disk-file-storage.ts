import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { FileStorage } from '../../application/files.js';

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

export class DiskFileStorage implements FileStorage {
  constructor(private readonly dir: string) {}

  async put(id: string, bytes: Uint8Array): Promise<void> {
    await mkdir(this.dir, { recursive: true });
    await writeFile(this.path(id), bytes);
  }

  async get(id: string): Promise<Uint8Array | null> {
    try {
      return await readFile(this.path(id));
    } catch {
      return null;
    }
  }

  private path(id: string): string {
    // ids are generated by us, but never let one walk out of the folder
    if (!UUID.test(id)) throw new Error(`invalid file id: ${id}`);
    return join(this.dir, id);
  }
}
